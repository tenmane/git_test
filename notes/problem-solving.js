// 1. Understand
// How to know when you understand a problem? When you can explain it in plain English.
// This is why you should write down your problem, doodle a diagram, or tell someone else about it.

// 2. Plan
// In programming, this means don’t start hacking straight away. 
// Give your brain time to analyze the problem and process the information.

// 3. Divide
// Break it into sub-problems. These sub-problems are much easier to solve.
// Solve each sub-problem one by one. Begin with the simplest. Simplest means you know the answer
// After that, simplest means this sub-problem being solved doesn’t depend on others being solved.